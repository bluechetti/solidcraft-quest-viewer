// Renders printable ASCII (32..126) in Helvetica to 1-bit bitmaps and writes src/font.rs.
// Usage: swift tools/make_font.swift > src/font.rs
import CoreGraphics
import CoreText
import Foundation

let height = 40          // bitmap rows per glyph
let fontSize: CGFloat = 32
let font = CTFontCreateWithName("Helvetica" as CFString, fontSize, nil)
let descent = CTFontGetDescent(font)

var out = "// Generated by tools/make_font.swift (Helvetica, \(Int(fontSize)) px). Do not edit.\n"
out += "/// Glyph rows, top first; bit (width - 1 - x) of a row is pixel x.\n"
out += "pub const FONT_H: usize = \(height);\n"
out += "/// (advance width in pixels, rows) for ASCII 32..=126.\n"
out += "pub static GLYPHS: [(u8, [u64; \(height)]); 95] = [\n"

for code in 32...126 {
    let ch = String(UnicodeScalar(UInt8(code)))
    let attr = NSAttributedString(string: ch, attributes: [
        NSAttributedString.Key(kCTFontAttributeName as String): font,
        NSAttributedString.Key(kCTForegroundColorFromContextAttributeName as String): true,
    ])
    let line = CTLineCreateWithAttributedString(attr)
    let advance = Int(ceil(CTLineGetTypographicBounds(line, nil, nil, nil)))
    let w = max(1, min(63, advance))
    let ctx = CGContext(data: nil, width: w, height: height, bitsPerComponent: 8, bytesPerRow: w,
                        space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
    ctx.setFillColor(gray: 0, alpha: 1)
    ctx.fill(CGRect(x: 0, y: 0, width: w, height: height))
    ctx.setFillColor(gray: 1, alpha: 1)
    ctx.textPosition = CGPoint(x: 0, y: ceil(descent) + 2)
    CTLineDraw(line, ctx)
    let data = ctx.data!.bindMemory(to: UInt8.self, capacity: w * height)
    var rows: [String] = []
    for r in 0..<height {  // CG memory row 0 is the top row
        var bits: UInt64 = 0
        for x in 0..<w where data[r * w + x] >= 175 {
            bits |= 1 << UInt64(w - 1 - x)
        }
        rows.append(String(format: "0x%x", bits))
    }
    out += "    (\(w), [\(rows.joined(separator: ", "))]), // \(code == 92 ? "backslash" : ch)\n"
}
out += "];\n"
print(out, terminator: "")
